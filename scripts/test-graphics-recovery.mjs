import assert from 'node:assert/strict';
import { buildSync } from 'esbuild';
import * as THREE from 'three';
buildSync({ stdin: { contents: `export * from './src/three/webglRecovery'; export * from './src/three/scenePerformance'; export * from './src/three/crayonMaterials';`, loader: 'ts', resolveDir: process.cwd() }, bundle: true, platform: 'node', format: 'esm', packages: 'external', outfile: '.npm-cache/graphics-recovery-test.mjs' });
const m = await import('../.npm-cache/graphics-recovery-test.mjs');
const canvas = new EventTarget(), page = new EventTarget(), doc = new EventTarget();
globalThis.window = page; globalThis.document = doc; doc.hidden = false;
const scene = new THREE.Scene(), gradient = m.getToonGradientMap();
const material = new THREE.MeshToonMaterial({ color: '#38bdf8', gradientMap: gradient });
const mesh = new THREE.Mesh(new THREE.BoxGeometry(), material); scene.add(mesh);
const light = new THREE.DirectionalLight(); light.shadow.map = new THREE.WebGLRenderTarget(8, 8); scene.add(light);
let shadowDisposed = 0, resumed = 0, restored = 0, restoreRequests = 0, contextLost = false, target;
light.shadow.map.addEventListener('dispose', () => shadowDisposed++);
const renderer = { domElement: canvas, shadowMap: { needsUpdate: false }, setRenderTarget: value => target = value, forceContextRestore: () => restoreRequests++, getContext: () => ({ isContextLost: () => contextLost }) };
const recovery = m.bindWebGLRecovery(renderer, scene, { resume: () => resumed++, restored: () => restored++ });
page.dispatchEvent(new Event('pageshow')); assert.equal(resumed, 1, 'Reopening repaints a paused scene');
doc.hidden = true; doc.dispatchEvent(new Event('visibilitychange')); assert.equal(resumed, 1);
doc.hidden = false; doc.dispatchEvent(new Event('visibilitychange')); assert.equal(resumed, 2);
const beforeVersion = gradient.version, beforeMaterial = material.version;
contextLost = true;
const loss = new Event('webglcontextlost', { cancelable: true }); canvas.dispatchEvent(loss);
assert(loss.defaultPrevented && !recovery.ready(), 'Loss pauses rendering and permits browser restoration');
page.dispatchEvent(new Event('pageshow')); assert.equal(restoreRequests, 1);
contextLost = false; canvas.dispatchEvent(new Event('webglcontextrestored'));
assert(recovery.ready()); assert.equal(restored, 1); assert.equal(resumed, 3); assert.equal(target, null);
assert(gradient.version > beforeVersion && material.version > beforeMaterial, 'Textures and shaders get fresh GPU resources');
assert.equal(shadowDisposed, 1); assert.equal(light.shadow.map, null); assert(renderer.shadowMap.needsUpdate);
recovery.dispose(); page.dispatchEvent(new Event('pageshow')); canvas.dispatchEvent(new Event('webglcontextlost', { cancelable: true }));
assert.equal(resumed, 3, 'Unmount removes recovery listeners and timers');
const otherScene = new THREE.Scene(), other = new THREE.Mesh(new THREE.BoxGeometry(), new THREE.MeshBasicMaterial()); otherScene.add(other);
const shared = m.addCrayonOutline(mesh).material; assert.equal(m.addCrayonOutline(other).material, shared);
let sharedDisposed = 0, ownedDisposed = 0;
shared.addEventListener('dispose', () => sharedDisposed++); other.material.addEventListener('dispose', () => ownedDisposed++);
m.disposeSceneGeometry(otherScene); assert.equal(sharedDisposed, 0, 'Closing one scene keeps outlines used by another scene'); assert.equal(ownedDisposed, 1);
m.disposeSceneGeometry(scene);
console.log('PASS: paused-scene reopen, visibility, context loss/restore, texture/shader/shadow recovery, timer/listener cleanup and cross-scene shared materials.');
